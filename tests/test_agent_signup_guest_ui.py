# tests/test_agent_signup_guest_ui.py
"""
Regression tests for agent/invite signup page UI.

Ensures guest pages (invite signup) do NOT show authenticated UI elements:
- No top nav icons (notifications, profile)
- No bottom nav (Home, Analytics, Scan, Sell, Menu)
- No sidebar
- Clean, mobile-friendly layout like the login page
"""

import pytest
from django.test import TestCase, Client
from django.contrib.auth import get_user_model
from django.urls import reverse
from tenants.models import Business, AgentInvite
from datetime import timedelta
from django.utils import timezone

User = get_user_model()


@pytest.mark.django_db
class AgentSignupGuestUITest(TestCase):
    """Test that guest signup pages don't show authenticated UI."""
    
    def setUp(self):
        """Create test business and invite."""
        self.client = Client()
        
        # Create a business
        self.business = Business.objects.create(
            name="Test Shop",
            slug="test-shop",
            status="ACTIVE"
        )
        
        # Create an invite - token will be auto-generated on save()
        self.invite = AgentInvite.objects.create(
            business=self.business,
            invited_name="Test Agent",
            email="agent@test.com",
            status="SENT",
            expires_at=timezone.now() + timedelta(hours=4)
        )
        
        # Get the token (auto-generated by model's save() method)
        self.token = self.invite.token
        assert self.token, "Token should be auto-generated by AgentInvite.save()"
    
    def test_guest_signup_page_accessible(self):
        """Test that anonymous users can access the invite signup page."""
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url)
        
        self.assertEqual(response.status_code, 200)
        self.assertContains(response, "Create your account")
    
    def test_guest_signup_no_bottom_nav(self):
        """Test that bottom nav is NOT shown for guest signup."""
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url)
        
        # Should NOT contain bottom nav labels
        content = response.content.decode('utf-8')
        
        # Check for mobile nav container (should NOT exist for guests)
        self.assertNotIn('mobile-tabbar', content.lower())
        self.assertNotIn('cc-bottom-nav', content)
        
        # Check that nav labels don't appear as standalone UI elements
        # (They might appear in URLs, but not as visible nav text)
        # Use more specific checks - look for the actual nav structure
        nav_patterns = [
            'bi-speedometer2',  # Home icon
            'bi-upc-scan',      # Scan icon
            'bi-cart-check',    # Sell icon
            'bi-box-seam',      # Stock icon
        ]
        
        # Count occurrences - these icons should NOT appear in nav context
        for pattern in nav_patterns:
            # If the pattern exists, it shouldn't be in a nav/tab structure
            if pattern in content:
                # Make sure it's not in a mobile nav tab
                self.assertNotIn(f'class="tab', content[max(0, content.find(pattern)-100):content.find(pattern)+100])
    
    def test_guest_signup_no_sidebar(self):
        """Test that sidebar is NOT shown for guest signup."""
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url)
        
        content = response.content.decode('utf-8')
        
        # Should NOT contain sidebar elements
        self.assertNotIn('cc-sidebar', content)
        self.assertNotIn('partials/sidebar', content)
        self.assertNotIn('id="sidebarOpen"', content)
    
    def test_guest_signup_no_topbar_icons(self):
        """Test that topbar icons (notifications, etc.) are NOT shown for guests."""
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url)
        
        content = response.content.decode('utf-8')
        
        # Should NOT contain notification bell
        self.assertNotIn('id="ccNotifBtn"', content)
        self.assertNotIn('bi-bell', content)
        
        # Should NOT contain tenant/business pill
        self.assertNotIn('tenant-pill', content)
        
        # Should NOT contain user profile menu
        self.assertNotIn('profile-menu', content)
    
    def test_guest_signup_has_form_fields(self):
        """Test that the signup form contains expected fields."""
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url)
        
        # Should contain signup form elements
        self.assertContains(response, 'name="name"')
        self.assertContains(response, 'name="email"')
        self.assertContains(response, 'name="password1"')
        self.assertContains(response, 'name="password2"')
        self.assertContains(response, 'type="submit"')
    
    def test_guest_signup_has_signin_link(self):
        """Test that signup page includes 'Already have an account?' link."""
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url)
        
        self.assertContains(response, "Already have an account")
        self.assertContains(response, "Sign in")
    
    def test_guest_signup_mobile_friendly(self):
        """Test that the page uses mobile-friendly viewport and layout."""
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url)
        
        content = response.content.decode('utf-8')
        
        # Should have mobile-friendly viewport meta
        self.assertIn('viewport', content.lower())
        
        # Should use responsive width (check for min() or responsive units)
        self.assertTrue(
            'min(' in content or 'clamp(' in content or '92vw' in content,
            "Page should use responsive width units"
        )
        
        # Should use dvh for full viewport height
        self.assertIn('dvh', content)
    
    def test_guest_signup_clean_centered_layout(self):
        """Test that page uses clean, centered card layout."""
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url)
        
        content = response.content.decode('utf-8')
        
        # Should use centered layout
        self.assertIn('place-items:center', content)
        
        # Should have card/container
        self.assertTrue(
            'class="card"' in content or 'cc-signup' in content,
            "Page should have a card/container element"
        )
    
    def test_authenticated_user_can_still_accept(self):
        """Test that authenticated users can also accept invites (edge case)."""
        # Create and login a user
        user = User.objects.create_user(username='testuser', password='test123')
        self.client.login(username='testuser', password='test123')
        
        url = reverse('tenants:invite_accept', args=[self.token])
        response = self.client.get(url, follow=True)
        
        # Should either show success or redirect to dashboard
        self.assertTrue(
            response.status_code == 200 or response.status_code == 302,
            "Authenticated users should be able to accept invites"
        )


@pytest.mark.django_db
class InviteAcceptFormSubmissionTest(TestCase):
    """Test the invite accept form submission for guests."""
    
    def setUp(self):
        """Create test business and invite."""
        self.client = Client()
        
        self.business = Business.objects.create(
            name="Test Shop",
            slug="test-shop",
            status="ACTIVE"
        )
        
        # Create invite - token will be auto-generated on save()
        self.invite = AgentInvite.objects.create(
            business=self.business,
            invited_name="Test Agent",
            email="agent@test.com",
            status="SENT",
            expires_at=timezone.now() + timedelta(hours=4)
        )
        
        # Get the auto-generated token
        self.token = self.invite.token
    
    def test_guest_can_submit_signup_form(self):
        """Test that guest can submit signup form with valid data."""
        url = reverse('tenants:invite_accept', args=[self.token])
        
        # Note: The view might use Django's UserCreationForm or custom form
        # Check the actual field names in tenants/views.py accept_invite()
        form_data = {
            'name': 'Test Agent',
            'email': 'agent@test.com',
            'password1': 'StrongPass123!@#',
            'password2': 'StrongPass123!@#',
        }
        
        response = self.client.post(url, form_data, follow=True)
        
        # Should either redirect to dashboard or show success
        self.assertTrue(
            response.status_code in [200, 302],
            f"Expected 200 or 302, got {response.status_code}"
        )
    
    def test_form_validation_password_mismatch(self):
        """Test that form validation catches password mismatch."""
        url = reverse('tenants:invite_accept', args=[self.token])
        
        form_data = {
            'name': 'Test Agent',
            'email': 'agent@test.com',
            'password1': 'StrongPass123!@#',
            'password2': 'DifferentPass456!@#',
        }
        
        response = self.client.post(url, form_data)
        
        # Should show error (form redisplayed with errors)
        self.assertEqual(response.status_code, 200)
        # The page should contain some error indication
        content = response.content.decode('utf-8')
        self.assertTrue(
            "don't match" in content.lower() or 'error' in content.lower(),
            "Should show password mismatch error"
        )


